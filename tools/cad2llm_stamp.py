#!/usr/bin/env python3
"""Generate a model-level vocabulary stamp plan from an export.

The plan writes cad2llm project metadata (project_id, vocab_version,
vocab_base_version, vocab_hash) into the SketchUp model dictionary. Apply it
with tools/cad2llm_bridge.py; the next export then carries the stamp inside
project_metadata.metadata.cad2llm.

Usage:
    python tools/cad2llm_stamp.py export.json --vocab project.vocab.json --out stamp.json
    python tools/cad2llm_stamp.py export.json --project-id house_test02 --json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cad2llm_vocab as vocab

SCHEMA = "cad2llm/annotate_plan/v1"
STAMP_KEYS = ("vocab_hash", "vocab_base_version", "vocab_version", "project_id")


def _current_metadata(doc: dict) -> dict:
    return (
        ((doc.get("project_metadata") or {}).get("metadata") or {}).get("cad2llm")
    ) or {}


def build_stamp_plan(
    doc: dict, vocab_data: dict, project_id: str | None = None
) -> dict:
    """Return a deterministic model-target plan (possibly with zero ops)."""
    fallback = ((doc.get("project_metadata") or {}).get("name")) or ""
    selected = (project_id or vocab_data.get("project_id") or fallback or "").strip()
    if not selected:
        raise ValueError("project_id is required (overlay, --project-id or model name)")

    desired = {
        "project_id": selected,
        "vocab_version": vocab_data.get("version"),
        "vocab_base_version": vocab_data.get("base_version")
        or vocab_data.get("version"),
        "vocab_hash": vocab.vocab_hash(vocab_data),
    }
    current = _current_metadata(doc)
    operations = []
    for key in STAMP_KEYS:
        value = desired[key]
        if value is None or current.get(key) == value:
            continue
        operations.append(
            {
                "op": "set_attribute",
                "target": {"kind": "model"},
                "dict": "cad2llm",
                "key": key,
                "value": value,
            }
        )

    plan = {
        "schema": SCHEMA,
        "name": f"vocab stamp: {selected}",
        "note": "Generated by tools/cad2llm_stamp.py. Model metadata only.",
        "transaction": "single",
        "operations": operations,
    }
    return {
        "plan": plan,
        "desired": desired,
        "current": {key: current.get(key) for key in STAMP_KEYS},
        "summary": {
            "project_id": selected,
            "vocab_version": desired["vocab_version"],
            "vocab_base_version": desired["vocab_base_version"],
            "vocab_hash": desired["vocab_hash"],
            "operations": len(operations),
            "already_stamped": not operations,
        },
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a model metadata stamp for a CAD2LLM export"
    )
    parser.add_argument("doc")
    parser.add_argument("--vocab", default=None, help="project vocabulary overlay")
    parser.add_argument("--project-id", default=None)
    parser.add_argument("--out", default=None)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    try:
        v = vocab.load_vocab(overlay=args.vocab)
        doc = json.loads(Path(args.doc).read_text(encoding="utf-8"))
        result = build_stamp_plan(doc, v, project_id=args.project_id)
    except (OSError, ValueError, TypeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        s = result["summary"]
        print(
            f"OK  project={s['project_id']} vocab={s['vocab_version']} "
            f"base={s['vocab_base_version']} hash={s['vocab_hash']} "
            f"operations={s['operations']}"
        )
        if s["already_stamped"]:
            print("    already stamped; no plan written")
        else:
            for op in result["plan"]["operations"]:
                print(f"    set {op['key']}={op['value']!r}")

    if args.out:
        if result["summary"]["already_stamped"]:
            print(f"    skipped {args.out} (nothing to change)")
        else:
            Path(args.out).write_text(
                json.dumps(result["plan"], indent=2, ensure_ascii=False) + "\n",
                encoding="utf-8",
            )
            print(f"    written {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
